import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';

const root=path.resolve(import.meta.dirname,'..');
const mode=process.argv[2]||'check';
const roots=['index.html','style.css','manifest.webmanifest','LICENSE','js','assets','vendor'];
async function inventory(){
  const files=[];
  async function walk(relative){
    const stat=await fs.lstat(path.join(root,relative));
    if(stat.isSymbolicLink())throw new Error('Public files must not be symlinks: '+relative);
    if(stat.isDirectory())for(const name of (await fs.readdir(path.join(root,relative))).sort())await walk(relative+'/'+name);
    else if(stat.isFile())files.push(relative);
  }
  for(const name of roots)await walk(name);
  return files.sort();
}
const files=await inventory(),digest=createHash('sha256');
for(const name of files){digest.update(name+'\0');digest.update(await fs.readFile(path.join(root,name)));}
const version=digest.digest('hex').slice(0,20);
const worker=`// SPDX-License-Identifier: Apache-2.0
// Generated by node scripts/site.mjs refresh; inventory is content-addressed.
const CACHE='street-racer-${version}';
const FILES=${JSON.stringify(['./',...files.map(f=>'./'+f)])};
const allowed=new Set(FILES.map(file=>new URL(file,self.registration.scope).href));
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(FILES))));
self.addEventListener('activate',event=>event.waitUntil((async()=>{
  for(const key of await caches.keys())if(key.startsWith('street-racer-')&&key!==CACHE)await caches.delete(key);
  await self.clients.claim();
})()));
self.addEventListener('fetch',event=>{
  const request=event.request,url=new URL(request.url);
  if(request.method!=='GET'||url.origin!==self.location.origin||!url.href.startsWith(self.registration.scope))return;
  if(request.mode==='navigate'){
    event.respondWith((async()=>{
      try{const response=await fetch(request);if(response.ok)return response;}catch{}
      return (await caches.open(CACHE)).match(new URL('./index.html',self.registration.scope));
    })());return;
  }
  url.search='';url.hash='';
  if(!allowed.has(url.href))return;
  event.respondWith(caches.open(CACHE).then(async cache=>(await cache.match(url.href))||fetch(request)));
});
`;
if(mode==='refresh'){
  await fs.writeFile(path.join(root,'sw.js'),worker);
  console.log(`Refreshed offline inventory: ${files.length} files / ${version}`);
}else if(mode==='check'||mode==='build'){
  const existing=await fs.readFile(path.join(root,'sw.js'),'utf8').catch(()=>null);
  if(existing!==worker)throw new Error('Offline inventory is stale. Run node scripts/site.mjs refresh and review sw.js.');
  const known=new Set(files);
  for(const name of files.filter(n=>n.endsWith('.js'))){
    const source=await fs.readFile(path.join(root,name),'utf8');
    for(const match of source.matchAll(/(?:from\s*|import\s*|import\s*\(\s*)['"](\.[^'"]+)['"]/g)){
      const target=path.posix.normalize(path.posix.join(path.posix.dirname(name),match[1]));
      if(!known.has(target))throw new Error(`Missing local import: ${name} -> ${target}`);
    }
  }
  console.log(`PASS: ${files.length} public files, all local module imports and offline inventory ${version}`);
  if(mode==='build'){
    const dest=path.resolve(root,process.argv[3]||'_site');
    if(dest!==path.join(root,'_site'))throw new Error('Build destination must be _site.');
    await fs.rm(dest,{recursive:true,force:true});await fs.mkdir(dest,{recursive:true});
    for(const name of [...files,'sw.js']){await fs.mkdir(path.dirname(path.join(dest,name)),{recursive:true});await fs.copyFile(path.join(root,name),path.join(dest,name));}
    await fs.writeFile(path.join(dest,'.nojekyll'),'');
    const bytes=(await Promise.all([...files,'sw.js'].map(name=>fs.stat(path.join(dest,name))))).reduce((sum,s)=>sum+s.size,0);
    console.log(`Staged ${files.length+2} files / ${bytes.toLocaleString('en-US')} bytes at _site`);
  }
}else throw new Error('Usage: node scripts/site.mjs refresh | check | build _site');
